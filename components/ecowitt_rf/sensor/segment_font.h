// Display wiring differs from Adafruit's segment numbering for the six inner strokes.
// a..f and g1/g2 are bits 0..7 on both. Inner strokes, Adafruit -> console:
// upper-left 8->11, upper-centre 9->8, upper-right 10->9,
// lower-left 11->13, lower-centre 12->12, lower-right 13->10.
constexpr uint16_t console_glyph(char c) {
    if (c < 32 || c > 126) return 0;
    const uint16_t m = ASCII14[static_cast<unsigned char>(c) - 32];
    return (m & 0xff) | ((m & 0x0100) << 3) | ((m & 0x0200) >> 1) |
           ((m & 0x0400) >> 1) | ((m & 0x0800) << 2) | (m & 0x1000) |
           ((m & 0x2000) >> 3);
}
constexpr uint8_t small_glyph(uint8_t code) {
    // Internal display codes: decimal, hex, settings letters, degree, lower-o, minus.
    constexpr char labels[] = "0123456789AbCdEFHILnOPU o- ";
    if (code == 23) return 0x63; // degree: upper square a,b,f,g
    return code < sizeof(labels) - 1 ? (ASCII7[labels[code] - 32] & 0x7f) : 0;
}
